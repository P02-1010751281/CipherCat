/**
 * FIPS 205 SLH-DSA.Sign（SHAKE 参数集，external 接口，pure 无预哈希，确定性）JavaScript 生成器。
 *
 * 约定（由 NIST ACVP SLH-DSA-sigGen-FIPS205 的 SHAKE f 参数集逐字节核对）：
 *   - M′ = 0x00 ‖ |ctx| ‖ ctx ‖ M；R = SHAKE256(SK.prf ‖ opt_rand ‖ M′, n)，opt_rand = PK.seed
 *   - 摘要 = SHAKE256(R ‖ PK.seed ‖ PK.root ‖ M′, ⌈k·a/8⌉+⌈(h−h′)/8⌉+⌈h′/8⌉)；
 *     FORS 的 k 个索引按 base_2^b 从摘要**MSB-first** 读取（SPHINCS+ 是 LSB-first，二者不同）
 *   - FORS：type 6（FORS_PRF）/ 3（FORS_TREE）/ 4（FORS_ROOTS），树内索引为**全局**索引
 *   - HT：layer 0 起自底向上，每层 xmss_sign（WOTS 签名 ‖ 认证路径），treeIndex 逐层右移 h′
 *   - 写 ADRS 必须先 setType 再写 type 专用字段（setType 会清零这些字段）
 */
import { javascriptGenerator, Order } from 'blockly/javascript';
import type { Block } from 'blockly/core';
import { registerSlhShake } from './slh-xmss';

/** SLH-DSA 参数集（SHAKE）：n, h, d, h′, a, k */
export const SLH_PARAM_SETS: Record<string, [number, number, number, number, number, number]> = {
  'SLH-DSA-SHAKE-128s': [16, 63, 7, 9, 12, 14],
  'SLH-DSA-SHAKE-128f': [16, 66, 22, 3, 6, 33],
  'SLH-DSA-SHAKE-192s': [24, 63, 7, 9, 14, 17],
  'SLH-DSA-SHAKE-192f': [24, 66, 22, 3, 8, 33],
  'SLH-DSA-SHAKE-256s': [32, 64, 8, 8, 14, 22],
  'SLH-DSA-SHAKE-256f': [32, 68, 17, 4, 9, 35],
};

export function registerSlhSign(): string {
  const shake = registerSlhShake();
  return javascriptGenerator.provideFunction_('slhSign', [
    'function ' + javascriptGenerator.FUNCTION_NAME_PLACEHOLDER_ + '(sk, message, context, paramSet) {',
    '  var SETS = ' + JSON.stringify(SLH_PARAM_SETS) + ';',
    '  var P = SETS[paramSet];',
    '  if (!P) throw new Error("SLH-DSA: unknown SHAKE parameter set " + paramSet);',
    '  var n = P[0], h = P[1], d = P[2], hp = P[3], a = P[4], k = P[5];',
    '  var skB = Array.from(sk);',
    '  if (skB.length !== 4 * n) throw new Error("SLH-DSA: secret key must be " + (4 * n) + " bytes for " + paramSet);',
    '  var ctxB = context == null ? [] : Array.from(context);',
    '  if (ctxB.length > 255) throw new Error("SLH-DSA context must be at most 255 bytes");',
    '  var msgB = Array.from(message);',
    '  var skSeed = skB.slice(0, n), skPrf = skB.slice(n, 2 * n), pkSeed = skB.slice(2 * n, 3 * n), pkRoot = skB.slice(3 * n);',
    '  function put32(x, off, val) { for (var i = 3; i >= 0; i--) { x[off + i] = val & 0xFF; val = Math.floor(val / 256); } }',
    '  function put96(x, val) { val = BigInt(val); for (var i = 11; i >= 0; i--) { x[4 + i] = Number(val & 255n); val >>= 8n; } }',
    '  function adrs(layer, tree, type) {',
    '    var x = new Array(32).fill(0);',
    '    put32(x, 0, layer); put96(x, tree); put32(x, 16, type);',
    '    return x;',
    '  }',
    '  function th(ad, m) { return Array.from(' + shake + '(pkSeed.concat(ad, Array.from(m)), n, 136)); }',
    '  function prf(ad) { return Array.from(' + shake + '(pkSeed.concat(ad, skSeed), n, 136)); }',
    '  function base2b(bytes, bits, outLen, offset) {',
    '    var out = [];',
    '    for (var i = 0; i < outLen; i++) {',
    '      var v = 0;',
    '      for (var j = 0; j < bits; j++) {',
    '        var off = offset + i * bits + j;',
    '        v = (v << 1) | ((bytes[off >> 3] >> (7 - (off & 7))) & 1);',
    '      }',
    '      out.push(v);',
    '    }',
    '    return out;',
    '  }',
    '  function chainLengths(m) {',
    '    var len1 = 2 * n, out = base2b(m, 4, len1, 0), csum = 0, i;',
    '    for (i = 0; i < len1; i++) csum += 15 - out[i];',
    '    csum <<= (8 - ((3 * 4) % 8)) % 8;',
    '    var cbytes = []; put32(cbytes, 0, csum);',
    '    return out.concat(base2b(cbytes.slice(-2), 4, 3, 0));',
    '  }',
    '  function wotsPk(kp, layer, tree) {',
    '    var length = 2 * n + 3, ad, i, j, v, chains = [];',
    '    for (i = 0; i < length; i++) {',
    '      ad = adrs(layer, tree, 5); put32(ad, 20, kp); put32(ad, 24, i); put32(ad, 28, 0);',
    '      v = prf(ad);',
    '      for (j = 0; j < 15; j++) { ad = adrs(layer, tree, 0); put32(ad, 20, kp); put32(ad, 24, i); put32(ad, 28, j); v = th(ad, v); }',
    '      chains.push(v);',
    '    }',
    '    var flat = [];',
    '    for (i = 0; i < length; i++) flat = flat.concat(chains[i]);',
    '    ad = adrs(layer, tree, 1); put32(ad, 20, kp);',
    '    return th(ad, flat);',
    '  }',
    '  function wotsSign(m, kp, layer, tree) {',
    '    var steps = chainLengths(m), length = 2 * n + 3, ad, i, j, v, sig = [];',
    '    for (i = 0; i < length; i++) {',
    '      ad = adrs(layer, tree, 5); put32(ad, 20, kp); put32(ad, 24, i); put32(ad, 28, 0);',
    '      v = prf(ad);',
    '      for (j = 0; j < 15; j++) {',
    '        if (j === steps[i]) sig = sig.concat(v);',
    '        ad = adrs(layer, tree, 0); put32(ad, 20, kp); put32(ad, 24, i); put32(ad, 28, j); v = th(ad, v);',
    '      }',
    '      if (steps[i] === 15) sig = sig.concat(v);',
    '    }',
    '    return sig;',
    '  }',
    '  function xmssSign(m, layer, tree, leafIdx) {',
    '    var count = 1 << hp, leaves = [], i, hh;',
    '    for (i = 0; i < count; i++) leaves.push(wotsPk(i, layer, tree));',
    '    var sig = wotsSign(m, leafIdx, layer, tree), level = leaves;',
    '    hh = 0;',
    '    while (level.length > 1) {',
    '      hh += 1;',
    '      var next = [];',
    '      for (i = 0; i < level.length; i += 2) {',
    '        var a2 = adrs(layer, tree, 2); put32(a2, 24, hh); put32(a2, 28, i >> 1);',
    '        next.push(th(a2, level[i].concat(level[i + 1])));',
    '      }',
    '      sig = sig.concat(level[(leafIdx >> (hh - 1)) ^ 1]);',
    '      level = next;',
    '    }',
    '    return { root: level[0], sig: sig };',
    '  }',
    '  function forsSign(md, layer, tree, leafIdx) {',
    '    var sig = [], roots = [], i, j;',
    '    for (i = 0; i < k; i++) {',
    '      var idxOffset = i * (1 << a);',
    '      var indices = base2b(md, a, k, 0);',
    '      var idx = indices[i];',
    '      var ad;',
    '      for (j = 0; j < (1 << a); j++) {',
    '        ad = adrs(layer, tree, 6); put32(ad, 20, leafIdx); put32(ad, 24, 0); put32(ad, 28, j + idxOffset);',
    '        var skv = prf(ad);',
    '        ad = adrs(layer, tree, 3); put32(ad, 20, leafIdx); put32(ad, 24, 0); put32(ad, 28, j + idxOffset);',
    '        if (j === idx) sig = sig.concat(skv);',
    '        var leaf = th(ad, skv);',
    '        if (j === 0) var level = [];',
    '        level.push(leaf);',
    '      }',
    '      var hh = 0;',
    '      while (level.length > 1) {',
    '        hh += 1;',
    '        var next = [];',
    '        for (j = 0; j < level.length; j += 2) {',
    '          var an = adrs(layer, tree, 3); put32(an, 20, leafIdx); put32(an, 24, hh); put32(an, 28, (j >> 1) + (idxOffset >> hh));',
    '          next.push(th(an, level[j].concat(level[j + 1])));',
    '        }',
    '        sig = sig.concat(level[(idx >> (hh - 1)) ^ 1]);',
    '        level = next;',
    '      }',
    '      roots.push(level[0]);',
    '    }',
    '    var flat = [];',
    '    for (i = 0; i < k; i++) flat = flat.concat(roots[i]);',
    '    var af = adrs(layer, tree, 4); put32(af, 20, leafIdx);',
    '    return { sig: sig, pk: th(af, flat) };',
    '  }',
    '  var mprime = [0x00, ctxB.length].concat(ctxB, msgB);',
    '  var optRand = pkSeed.slice();',
    '  var R = Array.from(' + shake + '(skPrf.concat(optRand, mprime), n, 136));',
    '  var forsBytes = Math.ceil((k * a) / 8), treeBytes = Math.ceil((h - hp) / 8), leafBytes = Math.ceil(hp / 8);',
    '  var digest = Array.from(' + shake + '(R.concat(pkSeed, pkRoot, mprime), forsBytes + treeBytes + leafBytes, 136));',
    '  var md = digest.slice(0, forsBytes);',
    '  var tree = 0n, i;',
    '  for (i = 0; i < treeBytes; i++) tree = (tree << 8n) | BigInt(digest[forsBytes + i]);',
    '  tree = tree & ((1n << BigInt(h - hp)) - 1n);',
    '  var leafIdx = 0;',
    '  for (i = 0; i < leafBytes; i++) leafIdx = leafIdx * 256 + digest[forsBytes + treeBytes + i];',
    '  leafIdx = leafIdx % (1 << hp);',
    '  var sigBytes = R.slice();',
    '  var fors = forsSign(md, 0, tree, leafIdx);',
    '  sigBytes = sigBytes.concat(fors.sig);',
    '  var m = fors.pk;',
    '  var tIdx = tree, lIdx = leafIdx;',
    '  for (i = 0; i < d; i++) {',
    '    var x = xmssSign(m, i, tIdx, lIdx);',
    '    sigBytes = sigBytes.concat(x.sig);',
    '    m = x.root;',
    '    lIdx = Number(tIdx & ((1n << BigInt(hp)) - 1n));',
    '    tIdx >>= BigInt(hp);',
    '  }',
    '  return sigBytes;',
    '}',
  ]);
}

javascriptGenerator.forBlock['slh_sign'] = function (block: Block): [string, number] {
  const sk = javascriptGenerator.valueToCode(block, 'SK', Order.ATOMIC) || '[]';
  const message = javascriptGenerator.valueToCode(block, 'MESSAGE', Order.ATOMIC) || '[]';
  const context = javascriptGenerator.valueToCode(block, 'CONTEXT', Order.ATOMIC) || '[]';
  const paramSet = block.getFieldValue('PARAM_SET') || 'SLH-DSA-SHAKE-128f';
  const fn = registerSlhSign();
  return [
    'Uint8Array.from(' + fn + '(' + sk + ', ' + message + ', ' + context + ', ' + JSON.stringify(paramSet) + '))',
    Order.ATOMIC,
  ];
};
