/**
 * FIPS 205 SLH-DSA.Sign（SHAKE 参数集，external、pure、确定性）Python 代码生成器。
 * 与 JS 生成器同构（约定见 slh-sign.ts 的 JS 版注释，已由 ACVP sigGen 向量逐字节核对）。
 */
import { pythonGenerator, Order } from 'blockly/python';
import type { Block } from 'blockly/core';
import { SLH_PARAM_SETS } from '../../javascript/hash/slh-sign';

export function registerSlhSign(): string {
  return pythonGenerator.provideFunction_('slh_sign', [
    'def ' + pythonGenerator.FUNCTION_NAME_PLACEHOLDER_ + '(sk, message, context, param_set):',
    '    import hashlib',
    '    PARAMS = {' + Object.entries(SLH_PARAM_SETS)
      .map(([name, p]) => `"${name}": ${JSON.stringify(p)}`)
      .join(', ') + '}',
    '    if param_set not in PARAMS:',
    '        raise ValueError("SLH-DSA: unknown SHAKE parameter set " + str(param_set))',
    '    n, h, d, hp, a, k = PARAMS[param_set]',
    '    sk = bytes(sk)',
    '    if len(sk) != 4 * n:',
    '        raise ValueError("SLH-DSA: secret key must be %d bytes for %s" % (4 * n, param_set))',
    '    ctxb = b"" if context is None else bytes(context)',
    '    if len(ctxb) > 255:',
    '        raise ValueError("SLH-DSA context must be at most 255 bytes")',
    '    msg = bytes(message)',
    '    sk_seed, sk_prf, pk_seed, pk_root = sk[:n], sk[n:2*n], sk[2*n:3*n], sk[3*n:]',
    '    def shake(data, out_len):',
    '        return hashlib.shake_256(data).digest(out_len)',
    '    def put32(x, off, val):',
    '        x[off:off+4] = int(val).to_bytes(4, "big")',
    '    def put96(x, val):',
    '        x[4:16] = int(val).to_bytes(12, "big")',
    '    def adrs(layer, tree, typ):',
    '        x = bytearray(32)',
    '        put32(x, 0, layer); put96(x, tree); put32(x, 16, typ)',
    '        return x',
    '    def th(ad, m):',
    '        return shake(pk_seed + bytes(ad) + bytes(m), n)',
    '    def prf(ad):',
    '        return shake(pk_seed + bytes(ad) + sk_seed, n)',
    '    def base2b(data, bits, out_len, offset):',
    '        out = []',
    '        for i in range(out_len):',
    '            v = 0',
    '            for j in range(bits):',
    '                off = offset + i * bits + j',
    '                v = (v << 1) | ((data[off >> 3] >> (7 - (off & 7))) & 1)',
    '            out.append(v)',
    '        return out',
    '    def chain_lengths(m):',
    '        len1 = 2 * n',
    '        out = base2b(m, 4, len1, 0)',
    '        csum = sum(15 - x for x in out)',
    '        csum <<= (8 - ((12 % 8))) % 8',
    '        cbytes = int(csum).to_bytes(4, "big")',
    '        return out + base2b(cbytes[-2:], 4, 3, 0)',
    '    def wots_pk(kp, layer, tree):',
    '        length = 2 * n + 3',
    '        chains = []',
    '        for i in range(length):',
    '            ad = adrs(layer, tree, 5); put32(ad, 20, kp); put32(ad, 24, i); put32(ad, 28, 0)',
    '            v = prf(ad)',
    '            for j in range(15):',
    '                ad = adrs(layer, tree, 0); put32(ad, 20, kp); put32(ad, 24, i); put32(ad, 28, j)',
    '                v = th(ad, v)',
    '            chains.append(v)',
    '        ad = adrs(layer, tree, 1); put32(ad, 20, kp)',
    '        return th(ad, b"".join(chains))',
    '    def wots_sign(m, kp, layer, tree):',
    '        steps = chain_lengths(m)',
    '        length = 2 * n + 3',
    '        sig = b""',
    '        for i in range(length):',
    '            ad = adrs(layer, tree, 5); put32(ad, 20, kp); put32(ad, 24, i); put32(ad, 28, 0)',
    '            v = prf(ad)',
    '            for j in range(15):',
    '                if j == steps[i]:',
    '                    sig += v',
    '                ad = adrs(layer, tree, 0); put32(ad, 20, kp); put32(ad, 24, i); put32(ad, 28, j)',
    '                v = th(ad, v)',
    '            if steps[i] == 15:',
    '                sig += v',
    '        return sig',
    '    def xmss_sign(m, layer, tree, leaf_idx):',
    '        count = 1 << hp',
    '        leaves = []',
    '        for i in range(count):',
    '            leaves.append(wots_pk(i, layer, tree))',
    '        sig = wots_sign(m, leaf_idx, layer, tree)',
    '        level = leaves',
    '        hh = 0',
    '        while len(level) > 1:',
    '            hh += 1',
    '            nxt = []',
    '            for i in range(0, len(level), 2):',
    '                an = adrs(layer, tree, 2); put32(an, 24, hh); put32(an, 28, i >> 1)',
    '                nxt.append(th(an, level[i] + level[i + 1]))',
    '            sig += level[(leaf_idx >> (hh - 1)) ^ 1]',
    '            level = nxt',
    '        return level[0], sig',
    '    def fors_sign(md, layer, tree, leaf_idx):',
    '        indices = base2b(md, a, k, 0)',
    '        sig = b""',
    '        roots = []',
    '        for i in range(k):',
    '            idx_offset = i * (1 << a)',
    '            idx = indices[i]',
    '            level = []',
    '            for j in range(1 << a):',
    '                ad = adrs(layer, tree, 6); put32(ad, 20, leaf_idx); put32(ad, 24, 0); put32(ad, 28, j + idx_offset)',
    '                skv = prf(ad)',
    '                ad2 = adrs(layer, tree, 3); put32(ad2, 20, leaf_idx); put32(ad2, 24, 0); put32(ad2, 28, j + idx_offset)',
    '                if j == idx:',
    '                    sig += skv',
    '                level.append(th(ad2, skv))',
    '            hh = 0',
    '            while len(level) > 1:',
    '                hh += 1',
    '                nxt = []',
    '                for j in range(0, len(level), 2):',
    '                    an = adrs(layer, tree, 3); put32(an, 20, leaf_idx); put32(an, 24, hh); put32(an, 28, (j >> 1) + (idx_offset >> hh))',
    '                    nxt.append(th(an, level[j] + level[j + 1]))',
    '                sig += level[(idx >> (hh - 1)) ^ 1]',
    '                level = nxt',
    '            roots.append(level[0])',
    '        af = adrs(layer, tree, 4); put32(af, 20, leaf_idx)',
    '        return sig, th(af, b"".join(roots))',
    '    mprime = b"\\x00" + bytes([len(ctxb)]) + ctxb + msg',
    '    R = shake(sk_prf + pk_seed + mprime, n)',
    '    fors_bytes = (k * a + 7) // 8',
    '    tree_bytes = (h - hp + 7) // 8',
    '    leaf_bytes = (hp + 7) // 8',
    '    digest = shake(R + pk_seed + pk_root + mprime, fors_bytes + tree_bytes + leaf_bytes)',
    '    md = digest[:fors_bytes]',
    '    tree = int.from_bytes(digest[fors_bytes:fors_bytes + tree_bytes], "big") % (1 << (h - hp))',
    '    leaf_idx = int.from_bytes(digest[fors_bytes + tree_bytes:], "big") % (1 << hp)',
    '    out = bytearray(R)',
    '    fors_sig, m = fors_sign(md, 0, tree, leaf_idx)',
    '    out += fors_sig',
    '    t_idx, l_idx = tree, leaf_idx',
    '    for i in range(d):',
    '        root, xsig = xmss_sign(m, i, t_idx, l_idx)',
    '        out += xsig',
    '        m = root',
    '        l_idx = t_idx % (1 << hp)',
    '        t_idx = t_idx >> hp',
    '    return list(out)',
  ]);
}

pythonGenerator.forBlock['slh_sign'] = function (block: Block): [string, number] {
  const sk = pythonGenerator.valueToCode(block, 'SK', Order.ATOMIC) || "b''";
  const message = pythonGenerator.valueToCode(block, 'MESSAGE', Order.ATOMIC) || "b''";
  const context = pythonGenerator.valueToCode(block, 'CONTEXT', Order.ATOMIC) || "b''";
  const paramSet = block.getFieldValue('PARAM_SET') || 'SLH-DSA-SHAKE-128f';
  const fn = registerSlhSign();
  return ['bytes(' + fn + '(' + sk + ', ' + message + ', ' + context + ', ' + JSON.stringify(paramSet) + '))', Order.ATOMIC];
};
